using System.Text.RegularExpressions;

namespace Bhoomisetu.Api.Documents;

/// <summary>
/// Where uploaded document files live. The database keeps only metadata and the storage key. Swap the local
/// folder for S3-compatible object storage in production by adding another implementation; nothing else changes.
/// </summary>
public interface IDocumentStorage
{
    Task SaveAsync(string key, Stream content, CancellationToken cancellationToken);

    /// <summary>The stored file, or null when it is missing.</summary>
    Task<Stream?> OpenReadAsync(string key, CancellationToken cancellationToken);

    Task DeleteAsync(string key, CancellationToken cancellationToken);
}

public sealed class DocumentOptions
{
    public const string SectionName = "Documents";

    /// <summary>Folder for the local storage; relative paths are under the app's content root.</summary>
    public string StoragePath { get; set; } = "data/documents";

    /// <summary>Documents one person may upload per day across all land.</summary>
    public int MaxUploadsPerUserPerDay { get; set; } = 30;

    /// <summary>Live (pending or approved) documents one person may have on one piece of land.</summary>
    public int MaxLivePerUploaderPerParcel { get; set; } = 20;
}

/// <summary>Files in one local folder. Keys are generated by the API and checked, so no path can escape it.</summary>
public sealed partial class LocalDocumentStorage : IDocumentStorage
{
    private readonly string _root;

    public LocalDocumentStorage(string root)
    {
        _root = Path.GetFullPath(root);
        Directory.CreateDirectory(_root);
    }

    public async Task SaveAsync(string key, Stream content, CancellationToken cancellationToken)
    {
        var path = PathFor(key);
        await using var file = new FileStream(path, FileMode.CreateNew, FileAccess.Write, FileShare.None, 81920, useAsync: true);
        await content.CopyToAsync(file, cancellationToken);
    }

    public Task<Stream?> OpenReadAsync(string key, CancellationToken cancellationToken)
    {
        var path = PathFor(key);
        Stream? stream = File.Exists(path) ? new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read, 81920, useAsync: true) : null;
        return Task.FromResult(stream);
    }

    public Task DeleteAsync(string key, CancellationToken cancellationToken)
    {
        File.Delete(PathFor(key));
        return Task.CompletedTask;
    }

    private string PathFor(string key)
    {
        if (!KeyPattern().IsMatch(key))
        {
            throw new ArgumentException("Invalid storage key.", nameof(key));
        }

        return Path.Combine(_root, key);
    }

    [GeneratedRegex(@"^[0-9a-f]{32}\.(pdf|jpg|png|webp)$")]
    private static partial Regex KeyPattern();
}
