-- 0007: public land documents, subscriptions and a WhatsApp contact number.
--
-- Business rules (see docs/decisions, items 25-28):
--   * Free visitors see the land facts and survey number; signing in (free) reveals a lister's WhatsApp.
--   * Owners and agents pay a subscription; while it is active buyers can contact them and they can upload documents.
--   * Only public papers are uploaded (brochure, site plan, HMDA/DTCP approval, RERA certificate, ...). Sale deeds,
--     ECs, passbooks, ROR-1B and ID cards are never uploaded; buyers see those with the seller in person.
--   * A document is shown to subscribed buyers only after a trust reviewer has looked at it.

-- WhatsApp number when it differs from the sign-in number. NULL means "use the sign-in number".
ALTER TABLE users ADD COLUMN whatsapp_e164 text CHECK (whatsapp_e164 ~ '^\+91[6-9][0-9]{9}$');

-- ---------------------------------------------------------------- subscriptions
-- One row per paid (or free) period. Renewals add a row that starts when the previous one ends.
-- Payments are taken outside the app for now and recorded by a reviewer with the payment reference.
CREATE TABLE subscriptions (
    id                 uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id            uuid        NOT NULL REFERENCES users (id),
    audience           text        NOT NULL CHECK (audience IN ('lister', 'viewer')),
    starts_at          timestamptz NOT NULL,
    ends_at            timestamptz NOT NULL,
    amount_paise       bigint      NOT NULL CHECK (amount_paise >= 0),
    payment_reference  text        NOT NULL CHECK (char_length(payment_reference) BETWEEN 1 AND 100),
    activated_by       uuid        NOT NULL REFERENCES users (id),
    cancelled_at       timestamptz,
    created_at         timestamptz NOT NULL DEFAULT now(),
    CHECK (ends_at > starts_at),
    CHECK (activated_by <> user_id)
);
CREATE INDEX subscriptions_user_idx ON subscriptions (user_id, audience, ends_at DESC);

-- ---------------------------------------------------------------- parcel documents
CREATE TABLE parcel_documents (
    id                uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    parcel_id         uuid        NOT NULL REFERENCES parcels (id) ON DELETE CASCADE,
    uploaded_by       uuid        NOT NULL REFERENCES users (id),
    doc_type          text        NOT NULL CHECK (doc_type IN
                          ('brochure', 'site_plan', 'location_map', 'layout_approval', 'rera_certificate', 'building_permission', 'site_photo')),
    reference_number  text        CHECK (char_length(reference_number) BETWEEN 2 AND 60),
    content_type      text        NOT NULL CHECK (content_type IN ('application/pdf', 'image/jpeg', 'image/png', 'image/webp')),
    size_bytes        integer     NOT NULL CHECK (size_bytes BETWEEN 1 AND 10485760),
    sha256            text        NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    -- Name of the stored file: generated by the API, never taken from the uploader.
    storage_key       text        NOT NULL UNIQUE CHECK (storage_key ~ '^[0-9a-f]{32}\.(pdf|jpg|png|webp)$'),
    status            text        NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected', 'removed')),
    review_note       text        CHECK (char_length(review_note) <= 1000),
    reviewed_by       uuid        REFERENCES users (id),
    reviewed_at       timestamptz,
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    CHECK (status NOT IN ('approved', 'rejected') OR (reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)),
    CHECK (reviewed_by IS NULL OR reviewed_by <> uploaded_by),
    CHECK (doc_type NOT IN ('layout_approval', 'rera_certificate', 'building_permission') OR reference_number IS NOT NULL),
    CHECK (doc_type <> 'site_photo' OR content_type <> 'application/pdf')
);
CREATE INDEX parcel_documents_parcel_idx ON parcel_documents (parcel_id, status);
CREATE INDEX parcel_documents_queue_idx ON parcel_documents (created_at) WHERE status = 'pending';
CREATE INDEX parcel_documents_uploader_idx ON parcel_documents (uploaded_by, created_at DESC);
-- The same file cannot be live twice on one parcel.
CREATE UNIQUE INDEX parcel_documents_no_repeat_idx ON parcel_documents (parcel_id, sha256) WHERE status IN ('pending', 'approved');
